/** Zones regroupées par quartier (pour les <optgroup>). */
export const ZONES_PAR_QUARTIER: { quartier: string; zones: Zone[] }[] = [
  ...new Set(ZONES.map((z) => z.quartier)),
].map((quartier) => ({
  quartier,
  zones: ZONES.filter((z) => z.quartier === quartier).sort((a, b) => a.zone.localeCompare(b.zone)),
}));

export function nomZone(id: number | null | undefined): string {
  return ZONES.find((z) => z.id === id)?.zone ?? '—';
}
